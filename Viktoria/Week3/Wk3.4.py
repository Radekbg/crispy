#Имаш списък от продукти и калории на порция. Искаш да извадиш продуктите с ≤ 200 kcal.

foods = [("ябълка", 95), ("банан", 120), ("кроасан", 300), ("кисело мляко", 160)]

low_cal = [name for name, kcal in foods if kcal <= 200]  #list comprehension — събира цикъл + условие в един ред.

print(low_cal)
