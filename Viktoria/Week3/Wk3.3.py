#Имаш два списъка: имена на продукти и налични бройки. Искаш списък от кортежи (tuple) (име, бройки), 
# но игнорираш липсващите двойки, ако списъците са с различна дължина

products = ["ябълки", "банани", "мляко", "ориз"]
counts = [10, 5, 2]
paired = []

for i in range(min(len(products), len(counts))):   #min за да спре цикълът при по-краткия списък
    paired.append((products[i], counts[i]))

print(paired)


# Резултат: [("ябълки", 10), ("банани", 5), ("мляко", 2)]